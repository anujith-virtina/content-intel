# -*- coding: utf-8 -*-
"""Repair the 5 new entries + pricing section on live post 38972.

They were published without their data-css typography tokens, so Thrive had
nothing to style them with and they rendered as oversized black text. This
removes those blocks from the live page and re-inserts them, generated by the
corrected build_entry_markup, which now carries every token.

DRY RUN by default. Pass 'publish' to write.
"""
import os, sys, re, io, json, base64, hashlib, urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from thrive_edit_lib import block_bounds, DIV_OPEN, DIV_CLOSE
from build_entry_markup import (build_entry, build_pricing_section,
                                parse_entries, parse_pricing_intro)
from apply_38972_additions import PRICES, LINKS, linkify, trailing_link

ROOT = r"C:\content-intel"
SRC_TXT = os.path.join(ROOT, r"clients\virtina\output\drafts\dropship-new-entries-2026-09-08.txt")
CSS_BK = os.path.join(ROOT, r"clients\virtina\output\backups\post-38972-tve_custom_css-2026-09-08.html")
PREVIEW = os.path.join(ROOT, r"clients\virtina\output\research\_38972_repair_preview.html")
POST_ID = 38972
DRY = "publish" not in sys.argv
NEW_NAMES = ["Dropshipping for WooCommerce (OPMC)", "ALD -", "TMDS -", "DropshipMe", "EPROLO"]

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36")


def headers():
    e = {}
    for ln in io.open(os.path.join(ROOT, ".env"), encoding="utf-8"):
        ln = ln.strip()
        if ln and "=" in ln and not ln.startswith("#"):
            k, v = ln.split("=", 1)
            e[k.strip()] = v.strip()
    tok = base64.b64encode(f"{e['WP_USERNAME']}:{e['WP_APP_PASSWORD']}".encode()).decode()
    return {"User-Agent": UA, "Content-Type": "application/json",
            "Authorization": "Basic " + tok}


def main():
    H = headers()
    live = json.load(urllib.request.urlopen(urllib.request.Request(
        f"https://virtina.com/wp-json/wp/v2/posts/{POST_ID}?context=edit",
        headers=H), timeout=300))
    src = live["meta"]["tve_updated_post"]
    print(f"live: {len(src)} chars, divs {len(DIV_OPEN.findall(src))}/{len(DIV_CLOSE.findall(src))}")

    out = src
    # remove the pricing section
    i = out.find('id="dropship-plugin-pricing"')
    if i != -1:
        s0 = out.rfind("<div", 0, i)
        b = block_bounds(out, i)
        e0 = b[1] if b else out.find("</div>\n</div>", i) + len("</div>\n</div>")
        out = out[:s0] + out[e0:]
        print("  removed the unstyled pricing section")

    # remove the 5 unstyled entries
    removed = 0
    for _ in range(len(NEW_NAMES)):
        hit = None
        for m in re.finditer(r'<h3[^>]*>(.*?)</h3>', out, re.S | re.I):
            t = re.sub("<[^>]+>", "", m.group(1)).strip()
            if any(n.lower() in t.lower() for n in NEW_NAMES):
                hit = m
                break
        if not hit:
            break
        b = block_bounds(out, hit.start())
        if not b:
            break
        out = out[:b[0]] + out[b[1]:]
        removed += 1
    print(f"  removed {removed} unstyled entries")

    left = [re.sub("<[^>]+>", "", m.group(1)).strip()
            for m in re.finditer(r'<h3[^>]*>(.*?)</h3>', out, re.S | re.I)]
    numbered = [t for t in left if re.match(r'^\d+\.', t)]
    print(f"  entries remaining: {len(numbered)}")
    if len(numbered) != 17:
        raise SystemExit(f"BLOCKING: expected 17 originals, found {len(numbered)}")

    # rebuild, this time WITH the typography tokens
    ents = parse_entries(SRC_TXT)
    heading, paras = parse_pricing_intro(SRC_TXT)
    blocks = []
    for i, (name, qas) in enumerate(ents, start=18):
        clean = []
        for q, a in qas:
            path = trailing_link(a)
            a2 = linkify(a)
            if path:
                a2 += f"  See our {LINKS[path]}: {path}"
            clean.append((q, a2))
        blocks.append(build_entry(i, name, clean))
    run = "".join(blocks)
    pricing = build_pricing_section(heading, [linkify(p) for p in paras], PRICES)

    last = None
    for m in re.finditer(r'<h3[^>]*>(.*?)</h3>', out, re.S | re.I):
        if re.match(r'^\d+\.', re.sub("<[^>]+>", "", m.group(1)).strip()):
            last = m
    b = block_bounds(out, last.start())
    out = out[:b[1]] + run + pricing + out[b[1]:]
    print(f"  re-inserted {len(ents)} entries + pricing, now with typography tokens")

    # guards
    css = io.open(CSS_BK, encoding="utf-8").read()
    emitted = set(re.findall(r'data-css="([^"]+)"', run + pricing))
    undefined = [t for t in emitted if t not in css]
    if undefined:
        raise SystemExit(f"BLOCKING: tokens not defined in the page CSS: {undefined}")
    if len(DIV_OPEN.findall(out)) != len(DIV_CLOSE.findall(out)):
        raise SystemExit("BLOCKING: div imbalance")
    if "&lt;table" in run + pricing:
        raise SystemExit("BLOCKING: escaped table markup would render as text")
    print(f"  all {len(emitted)} tokens defined in CSS | divs balanced | "
          f"{len(src)} -> {len(out)} chars")
    io.open(PREVIEW, "w", encoding="utf-8").write(out)

    if DRY:
        print("\nDRY RUN. Nothing pushed.")
        return

    r = urllib.request.urlopen(urllib.request.Request(
        f"https://virtina.com/wp-json/tcb/v1/posts/{POST_ID}/content",
        data=json.dumps({"tve_content": out}).encode("utf-8"),
        headers=H, method="POST"), timeout=300)
    print("THRIVE push:", r.status)
    urllib.request.urlopen(urllib.request.Request(
        f"https://virtina.com/wp-json/wp/v2/posts/{POST_ID}",
        data=json.dumps({"content": out}).encode("utf-8"),
        headers=H, method="POST"), timeout=300)
    back = json.load(urllib.request.urlopen(urllib.request.Request(
        f"https://virtina.com/wp-json/wp/v2/posts/{POST_ID}?context=edit",
        headers=H), timeout=300))
    print("  sha match:", hashlib.sha256(back["meta"]["tve_updated_post"].encode()).hexdigest()
          == hashlib.sha256(out.encode()).hexdigest(), "| status:", back["status"])


if __name__ == "__main__":
    main()
